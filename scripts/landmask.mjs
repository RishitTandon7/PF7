// one-off: rasterise natural earth land into a 180x90 bitmap so the globe has real continents without shipping a texture
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'
const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'))
const land = feature(topo, topo.objects.land)
const polys = []
for (const f of land.features ?? [land]) {
  const g = f.geometry
  if (g.type === 'Polygon') polys.push(g.coordinates)
  else for (const p of g.coordinates) polys.push(p)
}
const inRing = (x, y, ring) => {
  let c = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j]
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c
  }
  return c
}
const W = 180, H = 90
let bits = ''
for (let r = 0; r < H; r++) for (let c = 0; c < W; c++) {
  const lon = (c + 0.5) * (360 / W) - 180, lat = 90 - (r + 0.5) * (180 / H)
  let on = false
  for (const p of polys) { if (inRing(lon, lat, p[0]) && !p.slice(1).some((h) => inRing(lon, lat, h))) { on = true; break } }
  bits += on ? '1' : '0'
}
writeFileSync('src/data/landmask.js', `// generated by scripts/landmask.mjs. real natural earth land, ${W}x${H}\nexport const W = ${W}, H = ${H}\nexport const BITS = '${bits}'\n`)
console.log('land cells', bits.split('1').length - 1)
